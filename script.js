const canvas = document.querySelector("#signal-canvas");
const ctx = canvas.getContext("2d", { alpha: true });
const nav = document.querySelector("[data-nav]");
const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const languageButtons = document.querySelectorAll("[data-lang-option]");

const pointer = {
  x: window.innerWidth * 0.72,
  y: window.innerHeight * 0.34,
  active: false
};

let width = 0;
let height = 0;
let dpr = 1;
let nodes = [];
let frameId = 0;

function getNestedValue(source, path) {
  return path.split(".").reduce((value, key) => (value ? value[key] : undefined), source);
}

function setLanguage(language) {
  const dictionary = translations[language] || translations.en;
  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";
  document.title = dictionary.meta.title;
  document.querySelector('meta[name="description"]').setAttribute("content", dictionary.meta.description);

  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = getNestedValue(dictionary, element.dataset.i18n);
    if (value) {
      element.textContent = value;
    }
  });

  languageButtons.forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.langOption === language));
  });

  localStorage.setItem("portfolio-language", language);
}

function resizeCanvas() {
  dpr = Math.min(window.devicePixelRatio || 1, 2);
  width = window.innerWidth;
  height = window.innerHeight;
  canvas.width = Math.floor(width * dpr);
  canvas.height = Math.floor(height * dpr);
  canvas.style.width = `${width}px`;
  canvas.style.height = `${height}px`;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  createNodes();
}

function createNodes() {
  const count = Math.max(42, Math.min(96, Math.floor((width * height) / 18500)));
  nodes = Array.from({ length: count }, (_, index) => ({
    x: (index * 89 + Math.random() * width) % width,
    y: (index * 47 + Math.random() * height) % height,
    vx: (Math.random() - 0.5) * 0.34,
    vy: (Math.random() - 0.5) * 0.34,
    size: Math.random() * 1.8 + 0.6,
    pulse: Math.random() * Math.PI * 2
  }));
}

function drawGrid(time) {
  const step = 64;
  const offset = (time * 0.008) % step;
  ctx.strokeStyle = "rgba(180, 58, 78, 0.05)";
  ctx.lineWidth = 1;

  for (let x = -step + offset; x < width + step; x += step) {
    ctx.beginPath();
    ctx.moveTo(x, 0);
    ctx.lineTo(x, height);
    ctx.stroke();
  }

  for (let y = -step + offset; y < height + step; y += step) {
    ctx.beginPath();
    ctx.moveTo(0, y);
    ctx.lineTo(width, y);
    ctx.stroke();
  }
}

function drawNodes(time) {
  ctx.clearRect(0, 0, width, height);
  drawGrid(time);

  for (const node of nodes) {
    node.x += node.vx;
    node.y += node.vy;
    node.pulse += 0.018;

    if (node.x < -30) node.x = width + 30;
    if (node.x > width + 30) node.x = -30;
    if (node.y < -30) node.y = height + 30;
    if (node.y > height + 30) node.y = -30;

    const dx = pointer.x - node.x;
    const dy = pointer.y - node.y;
    const distance = Math.hypot(dx, dy);

    if (pointer.active && distance < 170) {
      node.x -= dx * 0.0018;
      node.y -= dy * 0.0018;
    }
  }

  for (let i = 0; i < nodes.length; i += 1) {
    for (let j = i + 1; j < nodes.length; j += 1) {
      const a = nodes[i];
      const b = nodes[j];
      const distance = Math.hypot(a.x - b.x, a.y - b.y);

      if (distance < 118) {
        const opacity = (1 - distance / 118) * 0.18;
        ctx.strokeStyle = `rgba(180, 58, 78, ${opacity})`;
        ctx.lineWidth = 1;
        ctx.beginPath();
        ctx.moveTo(a.x, a.y);
        ctx.lineTo(b.x, b.y);
        ctx.stroke();
      }
    }
  }

  for (const node of nodes) {
    const glow = 0.24 + Math.sin(node.pulse) * 0.1;
    ctx.fillStyle = `rgba(255, 143, 160, ${glow})`;
    ctx.beginPath();
    ctx.arc(node.x, node.y, node.size, 0, Math.PI * 2);
    ctx.fill();
  }

  frameId = window.requestAnimationFrame(drawNodes);
}

function updateNavState() {
  nav.classList.toggle("is-scrolled", window.scrollY > 12);
}

function revealOnScroll() {
  const observer = new IntersectionObserver(
    entries => {
      for (const entry of entries) {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      }
    },
    { threshold: 0.14, rootMargin: "0px 0px -48px 0px" }
  );

  document.querySelectorAll(".reveal").forEach(element => observer.observe(element));
}

languageButtons.forEach(button => {
  button.addEventListener("click", () => setLanguage(button.dataset.langOption));
});

window.addEventListener("resize", resizeCanvas, { passive: true });
window.addEventListener("scroll", updateNavState, { passive: true });
window.addEventListener(
  "pointermove",
  event => {
    pointer.x = event.clientX;
    pointer.y = event.clientY;
    pointer.active = true;
  },
  { passive: true }
);
window.addEventListener("pointerleave", () => {
  pointer.active = false;
});

setLanguage(localStorage.getItem("portfolio-language") || "en");
updateNavState();
revealOnScroll();

if (!reducedMotion) {
  resizeCanvas();
  frameId = window.requestAnimationFrame(drawNodes);
} else {
  window.cancelAnimationFrame(frameId);
}
